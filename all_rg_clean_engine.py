def cleanup_all_decompiled_temp_files(log_cb=None):
    """
    Cleans up all temporary decompiled folders, artifacts, and log files across
    all Intel FIT tools, workspace directories, and session temp folders.
    Prevents storage bloat and guarantees a clean, unjammed state on software startup/restart.
    """
    cleaned_count = 0
    app_root = Path(get_app_root())
    
    # 1. Clean temporary artifacts in external/FLASH System Tools
    flash_tools_dir = app_root / "external" / "FLASH System Tools"
    if flash_tools_dir.exists():
        for tool_dir in flash_tools_dir.iterdir():
            if not tool_dir.is_dir():
                continue
            
            # Check for subdirectories and files generated by FIT
            for child in list(tool_dir.iterdir()):
                try:
                    if child.is_dir():
                        c_lower = child.name.lower()
                        # If it has a Decomp folder, is named 'Int', starts with 'backup~', or is a decompiled bios folder
                        if (child / "Decomp").exists() or c_lower == "int" or c_lower.startswith("backup~"):
                            shutil.rmtree(str(child), ignore_errors=True)
                            cleaned_count += 1
                    elif child.is_file():
                        f_lower = child.name.lower()
                        # Clean temp map files, logs, outimage binaries generated during decompile/rebuild
                        if f_lower.endswith(".map") or f_lower in ("fit.log", "outimage.bin", "dummy_out.bin"):
                            child.unlink(missing_ok=True)
                            cleaned_count += 1
                except Exception:
                    pass

    # 2. Clean temporary decompiled directories in app root
    temp_dir_names = ["workspace", "temp", "backup_me", "extracted_firmware", "_decomp_workspace", "FIT_WORKSPACE"]
    for td in temp_dir_names:
        p = app_root / td
        if p.exists():
            try:
                shutil.rmtree(str(p), ignore_errors=True)
                cleaned_count += 1
            except Exception:
                pass

    if log_cb and cleaned_count > 0:
        log_cb(f"[CLEANUP] Purged {cleaned_count} temporary decompiled artifacts.")
    return cleaned_count


def get_xml_partition_input_file(xml_path, region_type: str = "BIOS"):
    """
    Extracts the exact input file path specified in the FIT XML configuration for a given region.
    Ensures replaced files maintain 100% exact matching filenames (case, spaces, suffix) with the decompiled files.
    """
    if not xml_path or not os.path.exists(str(xml_path)):
        return None
    try:
        with open(str(xml_path), "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        rtype = region_type.upper()
        if rtype == "BIOS":
            patterns = [
                r'<InputFile\s+value="([^"]+)"[^>]*label="BIOS Binary File"',
                r'<BiosRegion[^>]*>.*?<InputFile\s+value="([^"]+)"',
                r'<InputFile\s+value="([^"]*BIOS[^"]*\.bin)"'
            ]
        elif rtype in ("ME", "CSME", "CSE"):
            patterns = [
                r'<MeRegionFile\s+value="([^"]+)"',
                r'<CsmeRegionFile\s+value="([^"]+)"',
                r'<InputFile\s+value="([^"]+)"[^>]*label="Intel\(R\)\s+ME\s+Binary\s+File"',
                r'<(?:MeRegion|CsmeRegion)[^>]*>.*?<InputFile\s+value="([^"]+)"',
                r'<InputFile\s+value="([^"]*(?:ME\s+Sub|ME\s+Region|CSE\s+Region)[^"]*\.bin)"'
            ]
        elif rtype == "EC":
            patterns = [
                r'<InputFile\s+value="([^"]+)"[^>]*label="EC Binary File"',
                r'<EcRegion[^>]*>.*?<InputFile\s+value="([^"]+)"'
            ]
        elif rtype in ("GBE", "GBE2"):
            patterns = [
                r'<InputFile\s+value="([^"]+)"[^>]*label="GbE Binary File"',
                r'<GbeRegion[^>]*>.*?<InputFile\s+value="([^"]+)"'
            ]
        else:
            patterns = []

        for pat in patterns:
            match = re.search(pat, content, re.DOTALL | re.IGNORECASE)
            if match and match.group(1):
                raw = match.group(1).strip()
                if raw and raw.lower() != "none" and raw != "":
                    return Path(raw)
    except Exception:
        pass
    return None


def safe_path(p: str) -> str:
    """Returns extended-length path on Windows to avoid MAX_PATH (260) limitations."""
    if not p:
        return p
    p_abs = os.path.abspath(p)
    if os.name == 'nt' and not p_abs.startswith('\\\\?\\'):
        return '\\\\?\\' + p_abs
    return p_abs


def parse_dump_spi_regions(dump_bytes: bytearray) -> dict:
    """Parses SPI regions from Flash Descriptor table at 0x40."""
    regions = {}
    if len(dump_bytes) < 0x1000:
        return regions

    # Check FD signature at 0x10
    if dump_bytes[0x10:0x14] != b"\x5A\xA5\xF0\x0F":
        return regions

    reg_map = {
        0: "desc",
        1: "bios",
        2: "me",
        3: "gbe",
        8: "ec",
        9: "gbe2"
    }

    for i in range(16):
        entry_off = 0x40 + i * 4
        if entry_off + 4 > len(dump_bytes):
            break
        r_val = struct.unpack('<I', dump_bytes[entry_off:entry_off+4])[0]
        base = (r_val & 0x7FFF) << 12
        limit = ((r_val >> 16) & 0x7FFF) << 12 | 0xFFF
        if limit > base and (limit - base + 1) > 0x1000:
            name = reg_map.get(i, f"region_{i}")
            regions[name] = {
                "id": i,
                "name": name,
                "offset": base,
                "limit": limit,
                "size": limit - base + 1
            }

    return regions


def match_official_components(dump_path: str, extracted_files: list, log_cb=print) -> dict:
    """
    Scans and matches extracted components against the loaded backup dump.
    Returns a dictionary of matched items.
    """
    if not os.path.exists(safe_path(dump_path)) or not extracted_files:
        return {}

    with open(safe_path(dump_path), "rb") as f:
        dump_bytes = bytearray(f.read())

    regions = parse_dump_spi_regions(dump_bytes)
    
    # Run CSME Analyzer on dump
    dump_analyzer = R1CSMEAnalyzer(dump_path)
    dump_me = dump_analyzer.parse()
    dump_sku = (dump_me.get("sku") or "").upper()
    dump_ver = dump_me.get("version") or ""
    dump_cpu = (dump_me.get("cpu_gen") or "").upper()

    matches = {}

    bios_reg = regions.get("bios")
    me_reg = regions.get("me")
    ec_reg = regions.get("ec")
    gbe_reg = regions.get("gbe") or regions.get("gbe2")

    # 1. Match BIOS Region
    if bios_reg:
        target_size = bios_reg["size"]
        old_bios_slice = dump_bytes[bios_reg["offset"] : bios_reg["offset"] + target_size]
        old_tail64 = bytes(old_bios_slice[-64:]) if len(old_bios_slice) >= 64 else b""

        # Extract Board ID / BID patterns from backup dump for exact board variant matching
        detected_bids = set()
        for m in re.finditer(rb'(?<![A-Za-z0-9])(0[6789A-F][0-9A-F]{3,4})(?![A-Za-z0-9])', dump_bytes):
            detected_bids.add(m.group(1).decode('ascii', errors='ignore').upper())
        for m in re.finditer(rb'BID\s*[:=]?\s*([0-9A-F]{4,6})', dump_bytes, re.IGNORECASE):
            detected_bids.add(m.group(1).decode('ascii', errors='ignore').upper())

        from rg_engine.validator import validate_and_trim

        # Check for files that match the decompiled BIOS Region size EXACTLY (Byte-for-Byte)
        exact_size_files = []
        for f in extracted_files:
            try:
                if os.path.getsize(safe_path(f)) == target_size:
                    exact_size_files.append(f)
            except Exception:
                pass

        chosen_bios = None
        best_reason = ""
        best_score = 0

        # SCENARIO A: Exactly ONE file matches the exact byte size (No cutting / topper needed)
        if len(exact_size_files) == 1:
            chosen_bios = exact_size_files[0]
            best_score = 100000
            best_reason = "100% Exact Byte Size Match (Direct 1:1 Donor - No Cutting Needed)"
            log_cb(f"[INFO] Found single exact byte size matching donor: {os.path.basename(chosen_bios)} ({target_size} bytes). Direct replacement without cutting.")

        # SCENARIO B: MULTIPLE files match exact byte size (rank among them by Board ID & Reset Vector, no cutting)
        elif len(exact_size_files) > 1:
            log_cb(f"[INFO] Found {len(exact_size_files)} donor files matching exact byte size ({target_size} bytes). Ranking by Board ID & Reset Vector...")
            same_size_candidates = []
            for f in exact_size_files:
                fname = os.path.basename(f)
                score = 50000
                reasons = ["Exact Size Match"]

                # Board ID match in filename
                for bid in detected_bids:
                    if bid in fname.upper():
                        score += 20000
                        reasons.append(f"Board ID Matched ({bid})")
                        break

                # Reset Vector / footer tail match
                try:
                    with open(safe_path(f), "rb") as cf:
                        cf.seek(target_size - 64)
                        cand_tail = cf.read(64)
                    if old_tail64 and (cand_tail == old_tail64 or cand_tail[-16:] == old_tail64[-16:]):
                        score += 10000
                        reasons.append("Reset Vector Matched")
                except Exception:
                    pass

                same_size_candidates.append((score, f, target_size, ", ".join(reasons)))

            same_size_candidates.sort(key=lambda x: x[0], reverse=True)
            best_score, chosen_bios, best_sz, best_reason = same_size_candidates[0]
            log_cb(f"[INFO] Evaluated {len(same_size_candidates)} same-size candidates:")
            for sc, cf, csz, rsn in same_size_candidates:
                cname = os.path.basename(cf)
                tag = " [RECOMMENDED]" if cf == chosen_bios else ""
                log_cb(f"  • {cname} (Score: {sc}) -> {rsn}{tag}")

        # SCENARIO C: NO file matches exact size (all candidates are larger -> require Topper/Footer cutting)
        else:
            bios_candidates = []
            for f in extracted_files:
                try:
                    sz = os.path.getsize(safe_path(f))
                    fname = os.path.basename(f)
                    fname_lower = fname.lower()
                    if sz < target_size:
                        continue

                    score = 0
                    match_reasons = []

                    # Dry-run Topper & Footer Validation on candidate
                    dry_trimmed, h_rem, f_rem = validate_and_trim(
                        f, target_size, old_bios_region=old_bios_slice, log_callback=lambda x: None
                    )

                    if dry_trimmed is not None:
                        score += 10000
                        match_reasons.append(f"Topper Matched (Trimmed Top: {h_rem}B, Foot: {f_rem}B)")
                    else:
                        score -= 50000

                    # Board ID / BID matching in filename
                    for bid in detected_bids:
                        if bid in fname.upper():
                            score += 8000
                            match_reasons.append(f"Board ID Matched ({bid})")
                            break

                    bios_candidates.append((score, f, sz, ", ".join(match_reasons)))
                except Exception:
                    continue

            if bios_candidates:
                bios_candidates.sort(key=lambda x: x[0], reverse=True)
                best_score, chosen_bios, best_sz, best_reason = bios_candidates[0]
                if len(bios_candidates) > 1:
                    log_cb(f"[INFO] Evaluated {len(bios_candidates)} larger candidates requiring trimming:")
                    for sc, cf, csz, rsn in bios_candidates:
                        cname = os.path.basename(cf)
                        tag = " [RECOMMENDED]" if cf == chosen_bios else ""
                        log_cb(f"  • {cname} (Score: {sc}) -> {rsn}{tag}")

            matches["bios"] = {
                "title": "System BIOS Region",
                "file": chosen_bios,
                "filename": os.path.basename(chosen_bios),
                "size": bios_reg["size"],
                "offset": bios_reg["offset"],
                "score": best_score,
                "match_reason": best_reason,
                "target_desc": f"{bios_reg['size'] // (1024 * 1024)} MB (Offset: 0x{bios_reg['offset']:X})"
            }

    # Detect package flavor from chosen BIOS (e.g. RPL vs MTL) for multi-flavor packages
    flavor = ""
    if "bios" in matches:
        bfn = matches["bios"]["filename"].lower()
        for candidate_flavor in ["mtl", "rpl", "adl", "tgl", "cfl", "kbl", "skl"]:
            if candidate_flavor in bfn:
                flavor = candidate_flavor
                break

    # 2. Match CSME / ME Region
    me_candidates = []
    for f in extracted_files:
        try:
            fname = os.path.basename(f).lower()
            if "management engine" in fname or "csme" in fname or "me_region" in fname:
                score = 50
                if "consumer" in fname and "CON" in dump_sku:
                    score += 100
                elif "corporate" in fname and "COR" in dump_sku:
                    score += 100
                if dump_ver and dump_ver in fname:
                    score += 50
                if flavor and flavor in fname:
                    score += 200
                me_candidates.append((score, f))
            else:
                # Check for $FPT in first 1MB
                with open(safe_path(f), "rb") as mf:
                    header = mf.read(0x4000)
                    if b"$FPT" in header or b"\x24\x46\x50\x54" in header:
                        me_candidates.append((30, f))
        except Exception:
            continue

    if me_candidates:
        me_candidates.sort(key=lambda x: x[0], reverse=True)
        chosen_me = me_candidates[0][1]
        sz = os.path.getsize(safe_path(chosen_me))
        # Parse internal sub-partitions (PMC, PCHC, IOM) from FPT for informational display
        sub_info_list = []
        try:
            with open(safe_path(chosen_me), "rb") as mf:
                me_head = mf.read(0x8000)
            fpt_pos = me_head.find(b"\x24\x46\x50\x54")
            if fpt_pos != -1:
                entries = int.from_bytes(me_head[fpt_pos + 4 : fpt_pos + 8], "little")
                for i in range(min(entries, 64)):
                    off = fpt_pos + 32 + i * 32
                    p_name = me_head[off : off + 4].rstrip(b"\x00").decode("ascii", errors="ignore").strip()
                    if p_name in ("PMCP", "PMC") and "PMC" not in sub_info_list:
                        sub_info_list.append("PMC")
                    elif p_name == "PCHC" and "PCHC" not in sub_info_list:
                        sub_info_list.append("PCHC")
                    elif any(p == p_name for p in ("IOMP", "IOM", "NPHY", "TBTP")) and "Type-C IOM" not in sub_info_list:
                        sub_info_list.append("Type-C IOM")
        except Exception:
            pass

        sub_desc = f" (Includes {', '.join(sub_info_list)} Reset)" if sub_info_list else ""
        matches["me"] = {
            "title": f"CSME / ME Region{sub_desc}",
            "file": chosen_me,
            "filename": os.path.basename(chosen_me),
            "size": sz,
            "version": dump_ver,
            "sku": dump_sku,
            "target_desc": "Clean Factory ME (MFS -> Configured)",
            "op_desc": f"Clean Factory ME injection (PMC, PCHC, Type-C IOM automatically reset)"
        }

    # 3. Match Embedded Controller (EC)
    if ec_reg:
        ec_candidates = []
        for f in extracted_files:
            fname = os.path.basename(f).lower()
            if "embedded controller" in fname or fname.startswith("ec_") or "_ec." in fname:
                # Prefer main over backup
                score = 100
                if "backup" in fname:
                    score = 40
                if flavor and flavor in fname:
                    score += 200
                elif "mtl" in fname and "METEOR" in dump_cpu:
                    score += 30
                elif "rpl" in fname and ("RAPTOR" in dump_cpu or "ALDER" in dump_cpu):
                    score += 30
                ec_candidates.append((score, f))
        if ec_candidates:
            ec_candidates.sort(key=lambda x: x[0], reverse=True)
            chosen_ec = ec_candidates[0][1]
            matches["ec"] = {
                "title": "Embedded Controller (EC)",
                "file": chosen_ec,
                "filename": os.path.basename(chosen_ec),
                "size": os.path.getsize(safe_path(chosen_ec)),
                "offset": ec_reg["offset"],
                "target_desc": f"{ec_reg['size'] // 1024} KB (Offset: 0x{ec_reg['offset']:X})"
            }

    # 4. Match Gigabit Ethernet (GbE)
    if gbe_reg:
        gbe_candidates = []
        for f in extracted_files:
            fname = os.path.basename(f).lower()
            if "gigabit ethernet" in fname or "gbe" in fname:
                score = 50
                if "consumer" in fname and "CON" in dump_sku:
                    score += 50
                elif "corporate" in fname and "COR" in dump_sku:
                    score += 50
                if flavor and flavor in fname:
                    score += 200
                elif "mtl" in fname and "METEOR" in dump_cpu:
                    score += 20
                elif "rpl" in fname and ("RAPTOR" in dump_cpu or "ALDER" in dump_cpu):
                    score += 20
                gbe_candidates.append((score, f))
        if gbe_candidates:
            gbe_candidates.sort(key=lambda x: x[0], reverse=True)
            chosen_gbe = gbe_candidates[0][1]
            matches["gbe"] = {
                "title": "Gigabit Ethernet (GbE)",
                "file": chosen_gbe,
                "filename": os.path.basename(chosen_gbe),
                "size": os.path.getsize(safe_path(chosen_gbe)),
                "offset": gbe_reg["offset"],
                "target_desc": f"{gbe_reg['size'] // 1024} KB (Offset: 0x{gbe_reg['offset']:X})"
            }

    return matches


def perform_all_rg_clean(dump_path: str, matches: dict, output_path: str, log_cb=print) -> dict:
    """
    Executes surgical multi-region clean and replacement from matched components.
    """
    if not os.path.exists(safe_path(dump_path)):
        raise FileNotFoundError(f"Dump file not found: {dump_path}")

    with open(safe_path(dump_path), "rb") as f:
        data = bytearray(f.read())

    report = []
    log_cb("[ACTION] Starting ALL RG CLEAN Engine...")

    # 1. Replace BIOS Region
    bios_match = matches.get("bios")
    if bios_match:
        bios_file = bios_match["file"]
        offset = bios_match["offset"]
        target_size = bios_match["size"]
        with open(safe_path(bios_file), "rb") as bf:
            b_data = bf.read()

        # Handle trimming if needed
        if len(b_data) > target_size:
            # Check for standard headers or trailer
            diff = len(b_data) - target_size
            b_data = b_data[:target_size]

        if len(b_data) == target_size:
            data[offset : offset + target_size] = b_data
            msg = f"Replaced System BIOS Region at 0x{offset:X} (Size: {target_size // (1024 * 1024)} MB)"
            log_cb(f"[SUCCESS] {msg}")
            report.append(msg)
        else:
            log_cb(f"[WARNING] BIOS candidate size ({len(b_data)}) != target ({target_size}). Skipped.")

    # 2. Clean & Replace CSME Region (MFS Factory Reset)
    me_match = matches.get("me")
    if me_match:
        me_file = me_match["file"]
        with open(safe_path(me_file), "rb") as mf:
            clean_me_bytes = mf.read()

        # Find $FPT in dump to locate MFS
        fpt_sig = b"\x24\x46\x50\x54"
        fpt_offsets = []
        pos = 0
        while True:
            p = data.find(fpt_sig, pos)
            if p == -1: break
            fpt_offsets.append(p)
            pos = p + 4

        mfs_cleaned = False
        for fpt_pos in fpt_offsets:
            entries = int.from_bytes(data[fpt_pos+4 : fpt_pos+8], "little")
            if entries > 64: continue
            for i in range(entries):
                entry_offset = fpt_pos + 32 + i * 32
                entry = data[entry_offset : entry_offset + 32]
                p_name = entry[:4].rstrip(b"\x00").decode("ascii", errors="ignore")
                poff = int.from_bytes(entry[8:12], "little")
                psize = int.from_bytes(entry[12:16], "little")
                abs_part_offset = fpt_pos + poff

                if p_name == "MFS" and psize > 0:
                    # Check if clean_me_bytes has MFS partition
                    clean_mfs_chunk = None
                    clean_fpt = clean_me_bytes.find(fpt_sig)
                    if clean_fpt != -1:
                        c_entries = int.from_bytes(clean_me_bytes[clean_fpt+4 : clean_fpt+8], "little")
                        for ci in range(min(c_entries, 64)):
                            c_entry_off = clean_fpt + 32 + ci * 32
                            c_entry = clean_me_bytes[c_entry_off : c_entry_off + 32]
                            if c_entry[:4].rstrip(b"\x00").decode("ascii", errors="ignore") == "MFS":
                                c_poff = int.from_bytes(c_entry[8:12], "little")
                                c_psize = int.from_bytes(c_entry[12:16], "little")
                                if c_psize == psize:
                                    clean_mfs_chunk = clean_me_bytes[clean_fpt + c_poff : clean_fpt + c_poff + c_psize]
                                    break

                    if clean_mfs_chunk:
                        data[abs_part_offset : abs_part_offset + psize] = clean_mfs_chunk
                        log_cb(f"[INFO] Injected clean factory MFS partition at 0x{abs_part_offset:X} (0x{psize:X} bytes).")
                    else:
                        data[abs_part_offset : abs_part_offset + psize] = b"\xFF" * psize
                        log_cb(f"[INFO] Wiped runtime MFS partition at 0x{abs_part_offset:X} to 0xFF.")

                    mfs_cleaned = True

                elif p_name in ("FLOG", "ELOG", "EFS", "MFSB", "MDMV") and psize > 0:
                    data[abs_part_offset : abs_part_offset + psize] = b"\xFF" * psize
                    log_cb(f"[INFO] Reset runtime partition '{p_name}' at 0x{abs_part_offset:X} to 0xFF.")

        if mfs_cleaned:
            msg = "CSME runtime partitions cleaned and transitioned to Configured"
            log_cb(f"[SUCCESS] {msg}")
            report.append(msg)

    # 3. Replace EC Region
    ec_match = matches.get("ec")
    if ec_match:
        ec_file = ec_match["file"]
        offset = ec_match["offset"]
        target_size = ec_match.get("size", 0)
        with open(safe_path(ec_file), "rb") as ef:
            ec_data = ef.read()

        # If EC file is smaller than region size, pad with 0xFF or write as-is
        if len(ec_data) <= target_size:
            data[offset : offset + len(ec_data)] = ec_data
            if len(ec_data) < target_size:
                data[offset + len(ec_data) : offset + target_size] = b"\xFF" * (target_size - len(ec_data))
            msg = f"Injected clean Embedded Controller (EC) at 0x{offset:X}"
            log_cb(f"[SUCCESS] {msg}")
            report.append(msg)

    # 4. Replace GbE Region
    gbe_match = matches.get("gbe")
    if gbe_match:
        gbe_file = gbe_match["file"]
        offset = gbe_match["offset"]
        target_size = gbe_match.get("size", 0)
        with open(safe_path(gbe_file), "rb") as gf:
            gbe_data = gf.read()

        if len(gbe_data) <= target_size:
            data[offset : offset + len(gbe_data)] = gbe_data
            msg = f"Injected clean Gigabit Ethernet (GbE) at 0x{offset:X}"
            log_cb(f"[SUCCESS] {msg}")
            report.append(msg)

    # Save output file
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(safe_path(output_path), "wb") as out_f:
        out_f.write(data)

    # Verification
    try:
        analyzer = R1CSMEAnalyzer(output_path)
        ver_res = analyzer.parse()
        fs_state = ver_res.get("fs_stage") or ver_res.get("fs_state") or "Unknown"
        log_cb(f"[VERIFY] Final CSME File System State: {fs_state}")
    except Exception as ve:
        log_cb(f"[WARNING] Verification pass notice: {ve}")

